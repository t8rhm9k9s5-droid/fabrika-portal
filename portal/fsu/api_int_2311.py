def ask(prompt, imgs):
    for att in range(3):
        r = G.call('gptask', {'img': {'prompt': prompt, 'images': imgs, 'size': '1024x1536', 'quality': 'high'}})
        if not r.get('ok'): time.sleep(20); continue
        for i in range(150):
            time.sleep(8); g = G.call('gptget', {'id': r['id']})
            if g.get('status') in ('completed', 'failed', 'cancelled', 'incomplete'): break
        if g.get('images'): return base64.b64decode(g['images'][0])
        if 'credits' in str(g.get('err') or '') or 'billing' in str(g.get('err') or ''): return 'нет денег'
        time.sleep(10)
    return None


def model(code):
    x = GAP[code]; name, scene = SC[code]
    src = [p for p in ([x.get('best_source_photo')] + x.get('studio', [])) if p and os.path.exists(p)][:2]
    imgs = [du(p) for p in src]
    dp, np_ = os.path.join(OUT, code + '_day.png'), os.path.join(OUT, code + '_night.png')
    if not os.path.exists(dp):
        b = ask('На приложенных фото — реальное изделие: %s. Помести ЭТО изделие в интерьер: %s. Ясный день, мягкий естественный свет из окна. %s%s' % (name, scene, REAL, KEEP), imgs)
        if not isinstance(b, bytes): return code, 'день: ' + str(b)
        open(dp, 'wb').write(b)
    if not os.path.exists(np_):
        b = ask('Первое фото — интерьер днём. Сделай ТОТ ЖЕ самый кадр (та же комната, тот же ракурс, та же мебель, изделие на том же месте и без изменений) '
                'поздним вечером: за окном тёмное небо и огни города (без луны), холодный свет из окна, тёплый свет ламп в комнате, изделие хорошо читается, '
                'фон нейтральный, не синий. ' + REAL + KEEP, [du(dp)] + imgs[:1])
        if not isinstance(b, bytes): return code, 'ночь: ' + str(b)
        open(np_, 'wb').write(b)
    return code, 'готово'


if __name__ == '__main__':
    only = sys.argv[1:] or list(SC)
    with CF.ThreadPoolExecutor(5) as ex:
        for c, s in ex.map(model, only): print(c, s, flush=True)

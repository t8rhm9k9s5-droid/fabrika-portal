def scene(x):
    t = TIERS.get(x.get('_code'), {}).get('tier', 1)
    return (SCN.get(x['section'], DEF))[t]


def dims(code):   # 22.11.2026, Т. В.: «масштаб сверь по размерам предметов» — габариты из карточки сайта
    try:
        d = json.load(open('/home/claude/build/fsu/n/d/p/%s.json' % code, encoding='utf-8'))
        g = next((c['v'] for c in d.get('ch', []) if c.get('t') == 'Габариты'), [])
        v = {k: s.split('–')[0] for k, s in g if k in ('Ширина', 'Глубина', 'Высота')}
        return ('Реальные габариты: ширина %s, глубина %s, высота %s. Строго соблюдай масштаб относительно двери (~2100 мм), подоконника (~900 мм), стола (~750 мм), плитки пола; '
                'предмет стоит как в жизни — у стены, колонны или в нише по его размеру, на полу с контактной тенью. ' % (v.get('Ширина', '?'), v.get('Глубина', '?'), v.get('Высота', '?'))) if v else ''
    except Exception:
        return ''



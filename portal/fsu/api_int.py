import threading
_RL = threading.Lock()


def pick(code, lst):
    with _RL:
        return _pick(code, lst)


def _pick(code, lst):
    try: st = json.load(open(_ROT, encoding='utf-8'))
    except Exception: st = {}
    k = lst[0][:40]; d = st.setdefault(k, {'n': 0, 'by': {}})
    if code in d['by']: return lst[d['by'][code] % len(lst)]   # повторный запуск той же модели — та же сцена
    i = d['n'] % len(lst); d['by'][code] = i; d['n'] += 1
    json.dump(st, open(_ROT, 'w', encoding='utf-8'), ensure_ascii=False)
    return lst[i]



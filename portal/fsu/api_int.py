def spent():
    try: return sum(json.loads(l).get('usd', PRICE) for l in open(SPEND, encoding='utf-8') if l.strip())
    except Exception: return 0.0


def ask(prompt, imgs):
    if os.path.exists(STOPF): return 'стоп (Т. В.)'
    if spent() + PRICE > CAP: return 'лимит $%.0f исчерпан' % CAP
    b = _ask(prompt, imgs)
    if isinstance(b, bytes):
        with open(SPEND, 'a', encoding='utf-8') as f: f.write(json.dumps({'t': time.strftime('%d.%m %H:%M'), 'usd': PRICE}) + '\n')
    return b


def _ask(prompt, imgs):
    g = {}
    for att in range(3):
        r = G.call('gptask', {'img': {'prompt': prompt, 'images': imgs, 'size': '1024x1536', 'quality': 'high'}})
        if not r.get('ok'): time.sleep(20); continue
        for i in range(150):
            time.sleep(8); g = G.call('gptget', {'id': r['id']})
            if g.get('status') in ('completed', 'failed', 'cancelled', 'incomplete'): break
        if g.get('images'): return base64.b64decode(g['images'][0])
        if 'credits' in str(g.get('err') or '') or 'billing' in str(g.get('err') or ''): return 'нет денег'
        time.sleep(10)
    return None



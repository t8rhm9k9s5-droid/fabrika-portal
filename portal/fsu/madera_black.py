#!/usr/bin/env python3
"""«Мадера НВ», второй вариант — чёрный (Т. В. 25.11.2026): чёрные подлокотники, крестовина, ролики, газлифт; стол и окружение — с чёрными
акцентами. Заводского фото чёрного варианта нет: в запрос идут фото хромированного, перекрашиваются только металлические части.
Кадры: review/api/madera-nv-kreslo-black_day|night.png (визуализация)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import api_int as A
code = 'madera-nv-kreslo'; x = A.GAP[code]; d = A.card(code)
src = [p for p in ([x.get('best_source_photo')] + x.get('studio', [])) if p and os.path.exists(p)][:2]
imgs = [A.du(p) for p in src]
dp = os.path.join(A.OUT, code + '-black_day.png'); np_ = os.path.join(A.OUT, code + '-black_night.png')
VAR = ('ВАРИАНТ ИСПОЛНЕНИЯ: у этого кресла вместо хрома — ЧЁРНЫЕ детали. Подлокотники целиком чёрные (матовый чёрный металл с чёрной накладкой), '
       'пятилучевая крестовина чёрная матовая, газлифт (колонна) чёрный, ролики чёрные. Ни одной хромированной или блестящей серебристой детали у кресла нет. '
       'Всё остальное — строго как на заводском фото: та же форма и пропорции, та же светлая кремовая обивка со строчкой, та же тёмная спинка-корпус, тот же механизм. ')
SC = ('представительский интерьер: кабинет руководителя — рабочий стол высотой 750 мм с ЧЁРНОЙ матовой столешницей и чёрными металлическими опорами, '
      'кресло стоит у этого стола; вокруг чёрные акценты в тон: стеллаж из чёрного металла, чёрная настольная лампа, чёрные рамы окна и картин, чёрный торшер; '
      'стены светлые тёплые, пол — светлое дерево, чтобы кресло и чёрные акценты читались')
if not os.path.exists(dp):
    b = A.ask('На приложенных фото — реальное изделие «%s», реальные габариты: %s. Помести ЭТО изделие в %s. Ясный день, мягкий естественный свет из окна. %s%s%s' % (
        x['name'], A.dims(d), SC, VAR, A.REAL, A.REF), imgs)
    if not isinstance(b, bytes): print('день:', b); sys.exit(1)
    open(dp, 'wb').write(b)
if not os.path.exists(np_):
    b = A.ask('Первое фото — интерьер днём. Сделай ТОТ ЖЕ самый кадр (та же комната, тот же ракурс и масштаб, та же мебель, изделие на том же месте и без изменений) '
              'поздним вечером: за окном тёмное небо и огни города (без луны), холодный свет из окна, тёплый свет ламп в комнате, изделие хорошо читается, '
              'фон нейтральный, не синий. Цвет и форма изделия — точно как на этом дневном кадре: чёрные подлокотники, чёрная крестовина, чёрный газлифт, чёрные ролики.', [A.du(dp)])
    if not isinstance(b, bytes): print('ночь:', b); sys.exit(1)
    open(np_, 'wb').write(b)
print('готово', dp, np_)

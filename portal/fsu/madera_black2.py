#!/usr/bin/env python3
"""«Мадера НВ», чёрный вариант, попытка 2 (Т. В. 25.11: «кабинет вернуть тот, что был у хромированного; накладки подлокотников — как на фото»).
Основа — готовый дневной кадр хромированного варианта (та же комната и ракурс) + заводские фото как эталон формы подлокотника."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import api_int as A
code = 'madera-nv-kreslo'; x = A.GAP[code]
base = os.path.join(A.OUT, code + '_day.png'); ph = os.path.dirname(x['best_source_photo'])
imgs = [A.du(base), A.du(os.path.join(ph, 'main_madera_hb_1.png')), A.du(os.path.join(ph, 'main_madera_hb_2.png'))]
dp = os.path.join(A.OUT, code + '-black_day.png'); np_ = os.path.join(A.OUT, code + '-black_night.png')
if not os.path.exists(dp):
    b = A.ask('Первое фото — готовый кадр: кресло «Мадера НВ» в кабинете. Второе и третье — заводские фото этого кресла (эталон формы). '
              'Сделай ТОТ ЖЕ самый кадр: та же комната (тёмные деревянные панели, книжный шкаф с папками, дверь, окно со шторой, паркет ёлочкой), тот же ракурс и масштаб, '
              'кресло на том же месте, та же кремовая обивка со строчкой и тёмный корпус спинки. Меняется ТОЛЬКО отделка металла: '
              '1) у кресла вместо хрома — чёрный матовый металл: подлокотники, пятилучевая крестовина, газлифт; ролики чёрные; '
              '2) ФОРМА подлокотника — строго как на заводских фото и на первом кадре: плоская металлическая скоба-петля (теперь чёрная матовая) и сверху узкая чёрная накладка той же длины и толщины; '
              'не утолщай, не скругляй и не меняй накладку, не превращай подлокотник в пластиковый; '
              '3) в комнате акценты в тон: опоры стола — чёрный матовый металл вместо хрома (столешница остаётся деревянной), настольная лампа, подставка для ручек и дверная ручка — чёрные матовые. '
              'Больше ничего не меняй и не добавляй. Ни одной хромированной детали в кадре. Ясный день, мягкий свет из окна. Фотореалистично, вертикальный кадр 2:3, без людей, текста и логотипов.', imgs)
    if not isinstance(b, bytes): print('день:', b); sys.exit(1)
    open(dp, 'wb').write(b)
if not os.path.exists(np_):
    b = A.ask('Первое фото — интерьер днём. Сделай ТОТ ЖЕ самый кадр (та же комната, тот же ракурс и масштаб, та же мебель, изделие на том же месте и без изменений) '
              'поздним вечером: за окном тёмное небо и огни города (без луны), холодный свет из окна, тёплый свет ламп в комнате, изделие хорошо читается, '
              'фон нейтральный, не синий. Цвет и форма изделия — точно как на этом дневном кадре: чёрные матовые подлокотники с той же накладкой, чёрная крестовина, чёрный газлифт, чёрные ролики; опоры стола чёрные.', [A.du(dp)])
    if not isinstance(b, bytes): print('ночь:', b); sys.exit(1)
    open(np_, 'wb').write(b)
print('готово')

def on_page(c, doc):
    c.saveState()
    bar = 15 * mm
    c.setFillColor(RED); c.rect(0, H - bar, W, bar, fill=1, stroke=0)
    lh = 6.5 * mm; lw = 259 * lh / 59
    c.drawImage(_os.path.join(_SRC, "logo_on_red.png"), M, H - bar + (bar - lh) / 2, width=lw, height=lh)
    c.setFillColor(colors.white); c.setFont("DJB", 10)
    c.drawRightString(W - M, H - bar + 5.6 * mm, "Коммерческий отдел · базовый функционал")
    c.setFont("DJ", 7.5); c.setFillColor(MUTED)
    c.drawString(M, 9 * mm, "ГК «Фабрикант» · проект для обсуждения, октябрь 2026")
    c.drawRightString(W - M, 9 * mm, f"стр. {doc.page}")
    c.restoreState()

def person_block(name, boss, info):
    p = by_name(name)
    head = p["name"] in HEADS
    contacts = " · ".join(p["emails"] + p["phones"] + ([p["extra"]] if p["extra"] else []))
    if not (p["emails"] or p["phones"]):
        contacts = '<font color="#777777">Контактные данные пока не указаны</font>'
    hdr = Table([[Paragraph(p["name"], st["name"])],
                 [Paragraph(p["role"], st["role"])],
                 [Paragraph(contacts, st["cont"])]], colWidths=[W - 2 * M])
    hdr.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), GREY if head else colors.white),
        ("BOX", (0, 0), (-1, -1), 1.1, RED if head else LINE),
        ("LEFTPADDING", (0, 0), (-1, -1), 9), ("RIGHTPADDING", (0, 0), (-1, -1), 9),
        ("TOPPADDING", (0, 0), (0, 0), 7), ("BOTTOMPADDING", (0, -1), (-1, -1), 7),
        ("TOPPADDING", (0, 1), (-1, -1), 1), ("BOTTOMPADDING", (0, 0), (-1, -2), 1),
    ]))
    if info["duties"]:
        items = ListFlowable([ListItem(Paragraph(d, st["body"]), leftIndent=12, value="•") for d in info["duties"]],
                             bulletType="bullet", bulletFontName="DJ", bulletFontSize=9, bulletColor=RED_D, leftIndent=12)
    else:
        items = Paragraph("<i>Функционал пока не заполнен, запрошен у руководителя.</i>", st["body"])
    inner = [hdr, Spacer(1, 5),
             Paragraph(f"<b>Назначение роли.</b> {info['purpose']}", st["body"]),
             Paragraph(f"<b>Подчиняется:</b> {boss}" + ("" if boss.endswith(".") else "."), st["body"]),
             Paragraph("Основные функции", st["lab"]), items,
             Spacer(1, 3),
             Paragraph(f"<b>Взаимодействует:</b> {info['contacts']}", st["body"]),
             Paragraph(f"<b>Результат работы:</b> {info['kpi']}", st["body"]),
             Spacer(1, 14)]
    return KeepTogether(inner)


def by_name(name):
    d = DEPARTMENTS["sales"]
    for p in d["heads"] + d["staff"] + [d["subgroups"][0]["head"]] + d["subgroups"][0]["staff"]:
        if p["name"] == name: return p
    raise KeyError(name)


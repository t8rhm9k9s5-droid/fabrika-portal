DATE_RE = re.compile(r'(?<![\d№])(?P<pre>(?:\bот|\bс|\bпо|\bдо|\bк|\bна|\bв)\s+)?(?P<d>\d{1,2})\.(?P<m>\d{1,2})(?:\.(?P<y>\d{2,4}))?(?![\d])')
DATE_W = re.compile(r'(?P<pre>\b(?:до|к|на|в|по)\s+)?(?P<d>\d{1,2})\s+(?P<mon>' + '|'.join(MON) + r')', re.I)


def dates_in(t, d0):
    """→ [(date, start, end, kind)] — будущие (или сегодняшние) даты в тексте, относительно дня сообщения d0"""
    out = []
    for m in DATE_RE.finditer(t):
        pre = (m.group('pre') or '').strip().lower()
        if pre in ('от', 'с'): continue                                # «заказ от 30.09», «с 12 по 17» — ссылки, не сроки
        try:
            dd, mm = int(m.group('d')), int(m.group('m'))
            y = m.group('y'); yy = (2000 + int(y) if len(y) == 2 else int(y)) if y else d0.year
            d = datetime.date(yy, mm, dd)
            if not y and d < d0 - datetime.timedelta(days=180): d = datetime.date(yy + 1, mm, dd)
        except ValueError: continue
        if d0 - datetime.timedelta(days=1) <= d <= d0 + datetime.timedelta(days=120): out.append((d, m.start(), m.end(), 'date'))
    for m in DATE_W.finditer(t):
        pre = (m.group('pre') or '').strip().lower()
        try: d = datetime.date(d0.year, MON[m.group('mon').lower()], int(m.group('d')))
        except ValueError: continue
        if d < d0 - datetime.timedelta(days=180): d = d.replace(year=d.year + 1)
        if d0 <= d <= d0 + datetime.timedelta(days=120): out.append((d, m.start(), m.end(), 'date'))
    low = t.lower()
    def add(d, m, k): out.append((d, m.start(), m.end(), k))
    for m in re.finditer(r'\b(до|к|на)\s+кон(?:ец|ца|цу)\s+недел[иею]', low):
        f = d0 + datetime.timedelta(days=(4 - d0.weekday()) % 7); add(f, m, 'week')
    for m in re.finditer(r'\b(?:на\s+)?след(?:ующей|\.)?\s*недел[еию]', low):
        add(d0 + datetime.timedelta(days=(4 - d0.weekday()) % 7 + 7), m, 'nextweek')
    for m in re.finditer(r'\b(до|к|на)\s+кон(?:ец|ца|цу)\s+месяца', low):
        add(datetime.date(d0.year, d0.month, calendar.monthrange(d0.year, d0.month)[1]), m, 'month')
    for m in re.finditer(r'\bпослезавтра\b', low): add(next_workday(d0 + datetime.timedelta(days=2)), m, 'rel')
    for m in re.finditer(r'\bзавтра\b', low): add(next_workday(d0 + datetime.timedelta(days=1)), m, 'rel')
    for m in re.finditer(r'\b(в|на|к|до)\s+(?:след(?:ующ\w*|\.)?\s*)?(понедельник|вторник|среду|четверг|пятницу|субботу)\b', low):
        k = WD[m.group(2)]; d = d0 + datetime.timedelta(days=(k - d0.weekday()) % 7 or 7); add(d, m, 'wd')
    # an explicit date next to a relative word wins («в след. четверг 22.10»)
    out.sort(key=lambda x: (x[1], 0 if x[3] == 'date' else 1))
    res = []
    for x in out:
        if any(abs(x[1] - y[1]) < 25 and y[3] == 'date' and x[3] != 'date' for y in out): continue
        if not any(abs(x[1] - y[1]) < 3 for y in res): res.append(x)
    return res


def clauses(text):
    """строки и пункты списка; длинная строка — по предложениям"""
    out = []
    for line in re.split(r'\n+', text or ''):
        # 27.10.2026: Python хостинга (<3.7) не режет строку по пустому совпадению — режем по позициям сами
        cuts = sorted(set([0] + [m.start() for m in re.finditer(r'(?:(?<=\s)|^)(?=\d{1,2}[.)]\s*[А-ЯЁA-Z«"])', line) if m.start() > 0]))
        parts = [line[a:b] for a, b in zip(cuts, cuts[1:] + [len(line)])]
        for p in parts:
            p = p.strip()
            if not p: continue
            if len(p) > 260: out += [s.strip() for s in re.split(r'(?<=[.!?;])\s+(?=[А-ЯЁA-Z«"])', p) if s.strip()]
            else: out.append(p)
    return out


LEGAL = re.compile(r'^(ип|ооо|ао|зао|пао|оао|ук|гк|тд|ск|пк|нпо|мп|ч\.?п\.?)$', re.I)


def subj_key(cl):
    """клиент в начале пункта: «3. Ип Имя28 С. (Махачкала) — общались…» → ('каримов', 'с'); нет тире в начале — None"""
    m = re.match(r'^\s*(?:\d{1,2}[.)]\s*)?(?P<h>[^—\-–:]{2,60}?)\s*[—\-–:]', cl or '')
    if not m: return None
    ws = [w for w in re.findall(r'[A-Za-zА-Яа-яЁё0-9]+', m.group('h').lower().replace('ё', 'е')) if not LEGAL.match(w)]
    if not ws or len(ws[0]) < 3: return None
    return (ws[0], ws[1] if len(ws) > 1 else '')



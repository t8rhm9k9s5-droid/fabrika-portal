def upload_file(token, data, fname):
    """файл в MAX: POST /uploads?type=file → адрес загрузки → multipart (поле data) → token вложения. → (token, None) или (None, причина)"""
    code, j = api(token, 'POST', '/uploads', {'type': 'file'})
    url = j.get('url') if isinstance(j, dict) else None
    if not url: return None, 'uploads %s %s' % (code, str((j or {}).get('message') or '')[:80])
    b = '----t14' + hashlib.sha256(data).hexdigest()[:20]
    head = ('--%s\r\nContent-Disposition: form-data; name="data"; filename="%s"\r\nContent-Type: application/octet-stream\r\n\r\n'
            % (b, fname.replace('"', ''))).encode('utf-8')
    req = urllib.request.Request(url, data=head + data + ('\r\n--%s--\r\n' % b).encode('ascii'), method='POST',
                                 headers={'Content-Type': 'multipart/form-data; boundary=' + b})
    try:
        with urllib.request.urlopen(req, timeout=60, context=ssl.create_default_context()) as r: raw = r.read().decode('utf-8', 'replace')
    except urllib.error.HTTPError as e: return None, 'загрузка файла: %s' % e.code
    except Exception as e: return None, 'загрузка файла: %s' % (str(e)[:80] or e.__class__.__name__)
    try: rj = json.loads(raw or '{}')
    except ValueError: rj = {}
    tok = (rj.get('token') if isinstance(rj, dict) else None) or j.get('token')
    return (tok, None) if tok else (None, 'нет token после загрузки: %s' % raw[:80])



# (символы нулевой ширины: id в MAX). Если текст всплывёт пересланным или скопированным, find_mark() скажет, чья это копия.
# Скриншот метку не сохраняет. Отключить для сообщения — "mark": false в mx_direct.json.
ZW = ('\u200b', '\u200c')                                # 0 и 1
ZW_END = '\u2060'


def zw_mark(text, uid):
    try: n = int(uid)
    except Exception: return text
    bits = bin(n)[2:]
    code = ZW_END + ''.join(ZW[int(b)] for b in bits) + ZW_END
    t = str(text or '')
    i = t.find('\n')
    return (t[:i] + code + t[i:]) if i > 0 else (t + code)


def find_mark(text):
    """метка из текста → id в MAX (int) или None"""
    m = re.search(ZW_END + '([' + ''.join(ZW) + ']+)' + ZW_END, str(text or ''))
    if not m: return None
    return int(''.join('1' if c == ZW[1] else '0' for c in m.group(1)), 2)


